const getNestedValue = (value: unknown, key: string): unknown =>
  key.split('.').reduce<unknown>((current, part) => {
    if (current && typeof current === 'object' && part in current) {
      return (current as Record<string, unknown>)[part];
    }

    return undefined;
  }, value);

export const normalizeLanguage = (language: string): SupportedLang => {
  const normalized = language.toLowerCase();
  return SUPPORTED_LANGUAGES.find((supportedLanguage) => normalized.startsWith(supportedLanguage)) ?? DEFAULT_LANGUAGE;
};

export const getTranslation = (language: string, key: string) => {
  const locale = normalizeLanguage(language);
  const currentValue = getNestedValue(resources[locale].translation, key);

  if (typeof currentValue === 'string') {
    return currentValue;
  }

  const fallbackValue = getNestedValue(resources[DEFAULT_LANGUAGE].translation, key);
  return typeof fallbackValue === 'string' ? fallbackValue : key;
};
